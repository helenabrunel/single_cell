"""
16_collect_final_results.py
===============================
Curates the final TIM3 (HAVCR2) x hypoxia results -- both datasets, all
7 signatures -- into a single self-contained folder.
Pulls together, per dataset x signature, the outputs already generated by:

  Visvader:   08_TIM3_hypoxia_clean.py (violin stats, scatter, UMAP,
              proportions_stats added by 12_...)
              11_TIM3_hypoxia_clipped_violins.py (display-clipped violin)
              12_TIM3_hypoxia_reverse_comparison.py (barplot + proportions)

  Klughammer: 04_TIM3_hypoxia_clean.py (violin stats, scatter, UMAP)
              05_TIM3_hypoxia_clipped_violins.py (display-clipped violin)
              06_TIM3_hypoxia_reverse_comparison.py (barplot + proportions,
              saved into the 04_ folder)

Does not touch any source figures -- copies only. Also builds a
cross-signature summary CSV per dataset (pooled "All subtypes" panel) and
a top-level README.md.

Output: results_TIM3_hypoxia/
"""
import shutil
import pandas as pd
from pathlib import Path

ROOT = Path("/home/hbrunel/single_cell")

SIGNATURES = [
    "HALLMARK_HYPOXIA",
    "GO_0001666",
    "GAVISH_3CA_MALIGNANT_METAPROGRAM_6_HYPOXIA",
    "GOBP_REGULATION_OF_CELLULAR_RESPONSE_TO_HYPOXIA",
    "GOBP_HIF1A_SIGNALING_PATHWAY",
    "GOBP_NEG_REG_HYPOXIA_INDUCED_APOPTOTIC_SIGNALING",
    "GOBP_POS_REG_CELLULAR_RESPONSE_TO_HYPOXIA",
]

DATASETS = {
    "Visvader": {
        "clean_dir": ROOT / "Visvader/figures/08_TIM3_hypoxia_clean",
        "clipped_dir": ROOT / "Visvader/figures/11_TIM3_hypoxia_clipped",
        "out_dir": ROOT / "Visvader/results_TIM3_hypoxia",
        "compartment_label": "Epithelial",
    },
    "Klughammer": {
        "clean_dir": ROOT / "Klughammer/figures/04_TIM3_hypoxia_clean",
        "clipped_dir": ROOT / "Klughammer/figures/05_TIM3_hypoxia_clipped",
        "out_dir": ROOT / "Klughammer/results_TIM3_hypoxia",
        "compartment_label": "Malignant (epithelial-equivalent)",
    },
}

FILES_FROM_CLEAN = {
    "scatter_TIM3_hypoxia_naive.png": "scatter_magnitude_naive.png",
    "scatter_TIM3_hypoxia_depth_corrected.png": "scatter_magnitude_depth_corrected.png",
    "umap_overview.png": "umap_overview.png",
    "barplot_HAVCR2pct_by_hypoxia_group.png": "barplot_pct_HAVCR2_by_hypoxia_group.png",
    "violin_stats.csv": "stats_violin_HAVCR2_vs_hypoxia.csv",
    "correlation_comparison.csv": "stats_correlation_magnitude.csv",
    "proportions_stats.csv": "stats_proportions_by_hypoxia_group.csv",
}
FILE_FROM_CLIPPED = ("violin_clipped.png", "violin_HAVCR2_vs_hypoxia.png")

print("="*70)
print(" Building per-dataset results_TIM3_hypoxia/ folders")
print("="*70)

summary_rows = {name: [] for name in DATASETS}

for dset_name, cfg in DATASETS.items():
    print(f"\n{dset_name}:")
    clean_dir, clipped_dir = cfg["clean_dir"], cfg["clipped_dir"]
    dset_out = cfg["out_dir"]
    for sig in SIGNATURES:
        sig_out = dset_out / sig
        sig_out.mkdir(parents=True, exist_ok=True)

        src_clean = clean_dir / sig
        for src_name, dst_name in FILES_FROM_CLEAN.items():
            src = src_clean / src_name
            if src.exists():
                shutil.copy2(src, sig_out / dst_name)
            else:
                print(f"  [missing] {src}")

        src_clipped = clipped_dir / sig / FILE_FROM_CLIPPED[0]
        if src_clipped.exists():
            shutil.copy2(src_clipped, sig_out / FILE_FROM_CLIPPED[1])
        else:
            print(f"  [missing] {src_clipped}")

        # Pull "All subtypes" pooled row from each stats CSV for the summary table
        row = {"signature": sig}
        try:
            v = pd.read_csv(src_clean / "violin_stats.csv")
            v_all = v[v["panel"] == "All subtypes"].iloc[0]
            row["n_HAVCR2pos"] = int(v_all["n_pos"])
            row["n_HAVCR2neg"] = int(v_all["n_neg"])
            row["hypoxia_p_naive"] = v_all["p_naive"]
            row["hypoxia_p_depth_adj"] = v_all["p_depth_adjusted"]
            row["hypoxia_coef_depth_adj"] = v_all["coef_depth_adjusted"]
        except Exception as e:
            print(f"  [warn] violin_stats.csv for {sig}: {e}")

        try:
            c = pd.read_csv(src_clean / "correlation_comparison.csv")
            c_all = c[c["panel"] == "All HAVCR2+"].iloc[0]
            row["magnitude_r_naive"] = c_all["r_naive"]
            row["magnitude_p_naive"] = c_all["p_naive"]
            row["magnitude_r_depth_corrected"] = c_all["r_corrected"]
            row["magnitude_p_depth_corrected"] = c_all["p_corrected"]
        except Exception as e:
            print(f"  [warn] correlation_comparison.csv for {sig}: {e}")

        try:
            p = pd.read_csv(src_clean / "proportions_stats.csv")
            p_all = p[p["panel"] == "All subtypes"].iloc[0]
            row["pct_HAVCR2pos_hypoxia_low"] = p_all["pct_HAVCR2pos_low"]
            row["pct_HAVCR2pos_hypoxia_high"] = p_all["pct_HAVCR2pos_high"]
            row["proportions_OR_naive"] = p_all["odds_ratio_naive"]
            row["proportions_p_naive"] = p_all["p_naive"]
            row["proportions_OR_depth_adj"] = p_all["odds_ratio_depth_adjusted"]
            row["proportions_p_depth_adj"] = p_all["p_depth_adjusted"]
        except Exception as e:
            print(f"  [warn] proportions_stats.csv for {sig}: {e}")

        summary_rows[dset_name].append(row)
        print(f"  {sig}: files copied")

    summary_df = pd.DataFrame(summary_rows[dset_name])
    summary_df.to_csv(dset_out / "summary_all_signatures_pooled.csv", index=False)
    print(f"  Saved: {dset_out}/summary_all_signatures_pooled.csv")

print(f"\nDone.")
for dset_name, cfg in DATASETS.items():
    print(f"  {dset_name}: {cfg['out_dir']}/")
